#!/bin/bash
# Builds universal (arm64 + x86_64) static libusb and libmtp for macOS 14+
# into Vendor/. Homebrew's archives target the build machine's macOS and arch
# only, so they are not suitable for a distributable app.
set -euo pipefail

LIBUSB_VERSION=1.0.30
LIBMTP_VERSION=1.1.23
DEPLOYMENT_TARGET=14.0

for tool in pkg-config curl clang; do
    command -v "$tool" >/dev/null || { echo "error: $tool is required (brew install pkgconf)" >&2; exit 1; }
done

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
VENDOR="$ROOT/Vendor"
WORK="$ROOT/build/deps"
mkdir -p "$WORK" "$VENDOR/lib" "$VENDOR/include"

fetch() { # url dest
    [ -f "$2" ] || curl -fL --retry 3 -o "$2" "$1"
}

fetch "https://github.com/libusb/libusb/releases/download/v$LIBUSB_VERSION/libusb-$LIBUSB_VERSION.tar.bz2" \
      "$WORK/libusb.tar.bz2"
fetch "https://github.com/libmtp/libmtp/releases/download/v$LIBMTP_VERSION/libmtp-$LIBMTP_VERSION.tar.gz" \
      "$WORK/libmtp.tar.gz"

build_arch() { # arch
    local arch=$1 prefix="$WORK/prefix-$1" host
    [ "$arch" = arm64 ] && host=aarch64-apple-darwin || host=x86_64-apple-darwin
    export CC="clang -arch $arch -mmacosx-version-min=$DEPLOYMENT_TARGET"
    export CFLAGS="-O2"
    export PKG_CONFIG_PATH="$prefix/lib/pkgconfig"
    export PKG_CONFIG_LIBDIR="$prefix/lib/pkgconfig"

    rm -rf "$WORK/src-$arch" && mkdir -p "$WORK/src-$arch"
    tar -xf "$WORK/libusb.tar.bz2" -C "$WORK/src-$arch"
    tar -xf "$WORK/libmtp.tar.gz" -C "$WORK/src-$arch"

    (cd "$WORK/src-$arch/libusb-$LIBUSB_VERSION" &&
        ./configure --host=$host --prefix="$prefix" --enable-static --disable-shared >/dev/null &&
        make -j"$(sysctl -n hw.ncpu)" install >/dev/null)

    # mtpz needs libgcrypt; it is only used by old Zune devices.
    (cd "$WORK/src-$arch/libmtp-$LIBMTP_VERSION" &&
        ./configure --host=$host --prefix="$prefix" --enable-static --disable-shared \
            --disable-mtpz --with-udev=no >/dev/null &&
        make -j"$(sysctl -n hw.ncpu)" -C src install >/dev/null &&
        make install-data-am >/dev/null 2>&1 || true)
    # libmtp.h is generated by configure; install it explicitly.
    mkdir -p "$prefix/include"
    cp "$WORK/src-$arch/libmtp-$LIBMTP_VERSION/src/libmtp.h" "$prefix/include/"
}

build_arch arm64
build_arch x86_64

for lib in libusb-1.0.a libmtp.a; do
    lipo -create "$WORK/prefix-arm64/lib/$lib" "$WORK/prefix-x86_64/lib/$lib" -output "$VENDOR/lib/$lib"
done
cp "$WORK/prefix-arm64/include/libmtp.h" "$VENDOR/include/"
lipo -info "$VENDOR/lib/"*.a
echo "Vendor libraries ready in $VENDOR"
